import { cpSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { defineConfig } from "vite";

// ESM context — __dirname unavailable. Use import.meta.url instead.
// import.meta.dirname available from Node 21.2+; fileURLToPath is universal.
const __dirname = dirname(fileURLToPath(import.meta.url));

// ─── Helpers ─────────────────────────────────────────────────────────────────

/** Resolve path relative to project root (where this config lives). */
const r = (...segments: string[]) => resolve(__dirname, ...segments);

// ─── MPA page entries ─────────────────────────────────────────────────────────

/**
 * Locale entries — generated by `npm run prebuild`.
 * existsSync guard: first `vite dev` before prebuild won't crash.
 * en → pages/index.html (key "main"), ru/fi → pages/<loc>/index.html.
 */
const localeEntries = Object.fromEntries(
	(
		[
			["main", r("pages/index.html")],
			["ru", r("pages/ru/index.html")],
			["fi", r("pages/fi/index.html")],
		] as Array<[string, string]>
	).filter(([, path]) => existsSync(path)),
);

// 404 entry — built by prebuild
const notFoundEntries = existsSync(r("pages/404.html")) ? { "404": r("pages/404.html") } : {};

const staticEntries = {
	...localeEntries,
	...notFoundEntries,
};

