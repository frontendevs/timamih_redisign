// ─── Config ───────────────────────────────────────────────────────────────────

export default defineConfig({
	// Switch to "/" once custom domain timamih.com is active (DNS + Pages settings).
	base: "/timamih_redisign/",

	// HTML root: Vite serves and resolves assets relative to this directory.
	root: r("pages"),

	// Static assets copied as-is to dist/ (favicons, robots.txt, etc.).
	publicDir: r("public"),

	plugins: [
		{
			// Some image references may live in data-* attributes or runtime state,
			// so Vite can't detect them statically. Copy the image tree post-build.
			//
			// Remove this plugin if all image references are static imports
			// or if images are served from a CDN.
			name: "copy-product-images",
			closeBundle() {
				cpSync(r("pages/assets/images"), r("dist/assets/images"), { recursive: true });
			},
		},
	],

	build: {
		outDir: r("dist"),

		// Remove dist/ before each build — prevents stale files accumulating.
		emptyOutDir: true,

		// modulePreload: false — disable <link rel="modulepreload"> injection.
		//
		// MPA rationale: each page is a separate entry with its own small JS chunk.
		// Preloading cross-page chunks wastes bandwidth — users navigate to one page at a time.
		// Re-enable (remove this line) if the project shifts to a shared chunk strategy
		// or adds heavy dynamic imports within a single page.
		modulePreload: false,

		rollupOptions: {
			input: {
				...staticEntries,
				// ...productEntries, // uncomment if using auto-discovery
			},
		},
	},

	resolve: {
		alias: {
			// Must match tsconfig.json "paths" exactly.
			"@assets": r("pages/assets"),
			"@shared": r("pages/shared"),
		},
	},
});
