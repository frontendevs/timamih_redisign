/** Build inline SVG sprite string for injection into <body>. */
export function buildSprite(): string {
	const symbolsHtml = symbols
		.map(
			(s) =>
				`  <symbol id="icon-${s.id}" viewBox="${s.viewBox}" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${s.path}</symbol>`,
		)
		.join("\n");

	// hidden attribute hides the sprite without inline style (htmlhint compliance).
	// width/height=0 + hidden ensures zero layout space across all browsers.
	return `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" hidden aria-hidden="true">
${symbolsHtml}
</svg>`;
}
